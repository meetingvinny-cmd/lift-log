// A count: the '.one' key when n is 1 and that key exists, else the plain key (DESIGN 5.11 D.0).
// tn('count.sets', 1) -> '1 done set'; tn('count.sets', 4) -> '4 done sets'
export function tn(key, n, vals) {
  return t(n === 1 && (key + '.one') in S ? key + '.one' : key, { n, ...(vals || {}) });
}

// The parts of a filled string, so a screen can put each {name} value in its own span (LOOK 4.10
// range line): numSplit('range.line', {reps: 5, low: 8, high: 12}) -> [{num: '5'}, {text: ' reps. ...'}, ...].
// Joined, the parts are exactly t(key, vals).
export function numSplit(key, vals) {
  const out = [];
  for (const part of t(key).split(/(\{[a-z]+\})/)) {
    if (!part) continue;
    const m = /^\{([a-z]+)\}$/.exec(part);
    if (m && vals && m[1] in vals) out.push({ num: String(vals[m[1]]) });
    else out.push({ text: part });
  }
  return out;
}

// t('check.count', {n: 3, total: 7}) -> '3 of 7'
export function t(key, vals) {
  if (!(key in S)) throw new Error('strings: no key ' + key);
  let s = S[key];
  if (vals) for (const [k, v] of Object.entries(vals)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
